import React, { useState } from 'react';
import { 
  FileText, 
  Camera, 
  MapPin, 
  UserCheck, 
  Cpu, 
  ListTree, 
  Copy, 
  Check, 
  ExternalLink, 
  Download, 
  Search, 
  Info 
} from 'lucide-react';
import { useLanguage } from '../../i18n/useLanguage';
import type { ParsedMetadata } from '../../types/metadata';

interface InspectorViewProps {
  metadata: ParsedMetadata;
  onOpenExportModal: () => void;
}

type InspectorTab = 'overview' | 'camera' | 'location' | 'creator' | 'technical' | 'raw';

export const InspectorView: React.FC<InspectorViewProps> = ({ metadata, onOpenExportModal }) => {
  const { t } = useLanguage();
  const [activeTab, setActiveTab] = useState<InspectorTab>('overview');
  const [rawSearchQuery, setRawSearchQuery] = useState('');
  const [selectedRawCategory, setSelectedRawCategory] = useState<string>('ALL');
  const [copiedKey, setCopiedKey] = useState<string | null>(null);
  const [summaryCopied, setSummaryCopied] = useState(false);

  const { fileInfo, camera, location, creator, technical, rawTags } = metadata;

  const copyToClipboard = (text: string, key: string) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => setCopiedKey(null), 2000);
  };

  const handleCopySummary = () => {
    const lines: string[] = [
      `=== MoMetadata Summary ===`,
      `File: ${fileInfo.name}`,
      `Size: ${fileInfo.sizeFormatted}`,
      `Type: ${fileInfo.type}`,
      fileInfo.dimensions ? `Dimensions: ${fileInfo.dimensions.width}x${fileInfo.dimensions.height} px` : '',
      fileInfo.durationFormatted ? `Duration: ${fileInfo.durationFormatted}` : '',
      camera?.make || camera?.model ? `Camera: ${camera.make || ''} ${camera.model || ''}`.trim() : '',
      camera?.lens ? `Lens: ${camera.lens}` : '',
      camera?.iso ? `ISO: ${camera.iso}` : '',
      camera?.shutterSpeed ? `Shutter: ${camera.shutterSpeed}` : '',
      camera?.aperture ? `Aperture: ${camera.aperture}` : '',
      location?.hasGps ? `GPS: ${location.latitudeFormatted}, ${location.longitudeFormatted}` : '',
      creator?.title ? `Title: ${creator.title}` : '',
      creator?.artist || creator?.creator ? `Creator: ${creator.artist || creator.creator}` : '',
      creator?.copyright ? `Copyright: ${creator.copyright}` : '',
      `Total Metadata Tags: ${rawTags.length}`,
      `Generated by MoMetadata (https://mometadata.vercel.app)`
    ].filter(Boolean);

    navigator.clipboard.writeText(lines.join('\n'));
    setSummaryCopied(true);
    setTimeout(() => setSummaryCopied(false), 2500);
  };

  // Filter raw tags
  const rawCategories = ['ALL', ...Array.from(new Set(rawTags.map(t => t.category)))];
  const filteredRawTags = rawTags.filter(tag => {
    const matchesCat = selectedRawCategory === 'ALL' || tag.category === selectedRawCategory;
    const matchesQuery = 
      tag.tag.toLowerCase().includes(rawSearchQuery.toLowerCase()) ||
      tag.description.toLowerCase().includes(rawSearchQuery.toLowerCase()) ||
      tag.value.toLowerCase().includes(rawSearchQuery.toLowerCase());
    return matchesCat && matchesQuery;
  });

  const renderDataRow = (label: string, value?: string | number, keyName?: string) => {
    if (value === undefined || value === null || value === '') return null;
    const stringVal = String(value);
    const isCopied = copiedKey === (keyName || label);

    return (
      <div className="flex flex-col sm:flex-row sm:items-center justify-between py-2.5 px-3 rounded-lg hover:bg-slate-50 dark:hover:bg-slate-800/50 transition-colors border-b border-slate-100 dark:border-slate-800/40 last:border-0 gap-1 sm:gap-4">
        <span className="text-xs font-semibold text-slate-600 dark:text-slate-400 shrink-0">
          {label}
        </span>
        <div className="flex items-center gap-2 max-w-full overflow-hidden">
          <span className="text-xs font-semibold text-slate-900 dark:text-slate-100 break-all text-left sm:text-right">
            {stringVal}
          </span>
          <button
            onClick={() => copyToClipboard(stringVal, keyName || label)}
            className="p-1 rounded text-slate-400 hover:text-slate-700 dark:hover:text-slate-200 transition-colors cursor-pointer shrink-0"
            title={t.copyValue}
          >
            {isCopied ? <Check className="w-3.5 h-3.5 text-emerald-500" /> : <Copy className="w-3.5 h-3.5" />}
          </button>
        </div>
      </div>
    );
  };

  return (
    <div className="w-full glass-panel rounded-2xl p-4 sm:p-6 transition-all">
      {/* Top Action Bar */}
      <div className="flex flex-wrap items-center justify-between gap-3 mb-5 pb-4 border-b border-slate-200/80 dark:border-slate-800/80">
        <div className="flex items-center gap-2">
          <h3 className="text-base font-bold text-slate-900 dark:text-white flex items-center gap-2">
            <Info className="w-4 h-4 text-[#243A73] dark:text-blue-400" />
            {t.tabInspector}
          </h3>
          <span className="text-xs text-slate-600 dark:text-slate-400 font-medium">
            ({rawTags.length} tags discovered)
          </span>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleCopySummary}
            className="px-3 py-1.5 rounded-lg text-xs font-semibold border border-slate-200 dark:border-slate-700 bg-white/90 dark:bg-slate-800/80 hover:bg-slate-100 dark:hover:bg-slate-700 text-slate-800 dark:text-slate-200 transition-colors flex items-center gap-1.5 cursor-pointer"
          >
            {summaryCopied ? <Check className="w-3.5 h-3.5 text-emerald-500" /> : <Copy className="w-3.5 h-3.5" />}
            {summaryCopied ? t.summaryCopied : t.copySummary}
          </button>
          <button
            onClick={onOpenExportModal}
            className="px-3 py-1.5 rounded-lg text-xs font-semibold bg-[#243A73] hover:bg-[#1B2D5A] dark:hover:bg-[#304B91] text-white transition-colors flex items-center gap-1.5 cursor-pointer shadow-xs"
          >
            <Download className="w-3.5 h-3.5" />
            {t.exportReport}
          </button>
        </div>
      </div>

      {/* Tabs */}
      <div className="flex overflow-x-auto no-scrollbar gap-1.5 p-1 rounded-xl bg-slate-100/90 dark:bg-slate-800/80 mb-5">
        <button
          onClick={() => setActiveTab('overview')}
          className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer whitespace-nowrap
            ${activeTab === 'overview'
              ? 'bg-white dark:bg-slate-700 text-[#243A73] dark:text-blue-300 shadow-xs'
              : 'text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
            }`}
        >
          <FileText className="w-3.5 h-3.5" />
          {t.overviewTab}
        </button>

        <button
          onClick={() => setActiveTab('camera')}
          className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer whitespace-nowrap
            ${activeTab === 'camera'
              ? 'bg-white dark:bg-slate-700 text-[#243A73] dark:text-blue-300 shadow-xs'
              : 'text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
            }`}
        >
          <Camera className="w-3.5 h-3.5" />
          {t.cameraTab}
          {camera && <span className="w-1.5 h-1.5 rounded-full bg-emerald-500" />}
        </button>

        <button
          onClick={() => setActiveTab('location')}
          className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer whitespace-nowrap
            ${activeTab === 'location'
              ? 'bg-white dark:bg-slate-700 text-[#243A73] dark:text-blue-300 shadow-xs'
              : 'text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
            }`}
        >
          <MapPin className="w-3.5 h-3.5" />
          {t.locationTab}
          {location?.hasGps && <span className="w-1.5 h-1.5 rounded-full bg-amber-500" />}
        </button>

        <button
          onClick={() => setActiveTab('creator')}
          className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer whitespace-nowrap
            ${activeTab === 'creator'
              ? 'bg-white dark:bg-slate-700 text-[#243A73] dark:text-blue-300 shadow-xs'
              : 'text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
            }`}
        >
          <UserCheck className="w-3.5 h-3.5" />
          {t.creatorTab}
          {creator && <span className="w-1.5 h-1.5 rounded-full bg-blue-500" />}
        </button>

        <button
          onClick={() => setActiveTab('technical')}
          className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer whitespace-nowrap
            ${activeTab === 'technical'
              ? 'bg-white dark:bg-slate-700 text-[#243A73] dark:text-blue-300 shadow-xs'
              : 'text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
            }`}
        >
          <Cpu className="w-3.5 h-3.5" />
          {t.technicalTab}
        </button>

        <button
          onClick={() => setActiveTab('raw')}
          className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer whitespace-nowrap
            ${activeTab === 'raw'
              ? 'bg-white dark:bg-slate-700 text-[#243A73] dark:text-blue-300 shadow-xs'
              : 'text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white'
            }`}
        >
          <ListTree className="w-3.5 h-3.5" />
          {t.rawTagsTab} ({rawTags.length})
        </button>
      </div>

      {/* Tab Contents */}
      <div className="space-y-2">
        {/* 1. OVERVIEW */}
        {activeTab === 'overview' && (
          <div className="space-y-1">
            {renderDataRow(t.fileName, fileInfo.name)}
            {renderDataRow(t.fileSize, fileInfo.sizeFormatted)}
            {renderDataRow(t.fileType, fileInfo.type)}
            {fileInfo.dimensions && renderDataRow(t.dimensions, `${fileInfo.dimensions.width} × ${fileInfo.dimensions.height} px`)}
            {fileInfo.durationFormatted && renderDataRow(t.duration, fileInfo.durationFormatted)}
            {camera?.software && renderDataRow(t.software, camera.software)}
            {renderDataRow('Total Discovered Metadata Tags', rawTags.length)}
          </div>
        )}

        {/* 2. CAMERA & OPTICS */}
        {activeTab === 'camera' && (
          <div className="space-y-1">
            {camera ? (
              <>
                {renderDataRow(t.cameraMake, camera.make)}
                {renderDataRow(t.cameraModel, camera.model)}
                {renderDataRow(t.lensModel, camera.lens)}
                {renderDataRow(t.iso, camera.iso)}
                {renderDataRow(t.shutterSpeed, camera.shutterSpeed)}
                {renderDataRow(t.aperture, camera.aperture)}
                {renderDataRow(t.focalLength, camera.focalLength)}
                {renderDataRow(t.orientation, camera.orientation)}
                {renderDataRow(t.deviceSerial, camera.serialNumber)}
                {renderDataRow(t.software, camera.software)}
              </>
            ) : (
              <div className="py-8 text-center text-xs text-slate-500 dark:text-slate-400">
                {t.noCategoryData}
              </div>
            )}
          </div>
        )}

        {/* 3. LOCATION & GPS */}
        {activeTab === 'location' && (
          <div className="space-y-3">
            {location && location.hasGps ? (
              <>
                <div className="space-y-1">
                  {renderDataRow(t.gpsLatitude, location.latitudeFormatted)}
                  {renderDataRow(t.gpsLongitude, location.longitudeFormatted)}
                  {location.altitudeFormatted && renderDataRow(t.gpsAltitude, location.altitudeFormatted)}
                </div>

                {location.mapUrl && (
                  <div className="mt-4 p-4 rounded-xl border border-amber-200 dark:border-amber-900/60 bg-amber-50/70 dark:bg-amber-950/20 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3">
                    <div>
                      <h4 className="text-xs font-bold text-amber-900 dark:text-amber-200">
                        {t.openInMap}
                      </h4>
                      <p className="text-[11px] text-amber-700 dark:text-amber-300 mt-0.5">
                        {t.mapDisclaimer}
                      </p>
                    </div>
                    <a
                      href={location.mapUrl}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="px-3.5 py-1.5 rounded-lg text-xs font-semibold bg-[#243A73] hover:bg-[#1B2D5A] dark:hover:bg-[#304B91] text-white transition-colors flex items-center gap-1.5 shrink-0"
                    >
                      <ExternalLink className="w-3.5 h-3.5" />
                      OpenStreetMap
                    </a>
                  </div>
                )}
              </>
            ) : (
              <div className="py-8 text-center text-xs text-slate-500 dark:text-slate-400">
                {t.noCategoryData}
              </div>
            )}
          </div>
        )}

        {/* 4. CREATOR & RIGHTS */}
        {activeTab === 'creator' && (
          <div className="space-y-1">
            {creator ? (
              <>
                {renderDataRow(t.titleLabel, creator.title)}
                {renderDataRow(t.artistLabel, creator.artist || creator.creator || creator.author)}
                {renderDataRow(t.copyrightLabel, creator.copyright)}
                {renderDataRow(t.descriptionLabel, creator.description)}
                {renderDataRow(t.albumLabel, creator.album)}
                {renderDataRow(t.yearLabel, creator.year)}
                {renderDataRow(t.genreLabel, creator.genre)}
                {renderDataRow(t.commentsLabel, creator.comments)}
                {creator.keywords && creator.keywords.length > 0 && 
                  renderDataRow('Keywords', creator.keywords.join(', '))}
              </>
            ) : (
              <div className="py-8 text-center text-xs text-slate-500 dark:text-slate-400">
                {t.noCategoryData}
              </div>
            )}
          </div>
        )}

        {/* 5. TECHNICAL */}
        {activeTab === 'technical' && (
          <div className="space-y-1">
            {technical || fileInfo.type ? (
              <>
                {renderDataRow('Container / Format', technical?.containerFormat || fileInfo.extension.toUpperCase())}
                {renderDataRow('MIME Type', fileInfo.type)}
                {renderDataRow('Color Profile / Space', technical?.colorSpace || technical?.profileName)}
                {renderDataRow('Resolution', technical?.xResolution ? `${technical.xResolution} dpi` : undefined)}
                {renderDataRow('Audio Codec', technical?.audioCodec)}
                {renderDataRow('Sample Rate', technical?.sampleRate ? `${technical.sampleRate} Hz` : undefined)}
                {renderDataRow('Audio Channels', technical?.channels)}
                {renderDataRow('Video Codec', technical?.videoCodec)}
              </>
            ) : (
              <div className="py-8 text-center text-xs text-slate-500 dark:text-slate-400">
                {t.noCategoryData}
              </div>
            )}
          </div>
        )}

        {/* 6. RAW TAGS TABLE */}
        {activeTab === 'raw' && (
          <div>
            {/* Search and Category Filter */}
            <div className="flex flex-col sm:flex-row gap-2 mb-3">
              <div className="relative flex-1">
                <Search className="w-3.5 h-3.5 absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
                <input
                  type="text"
                  placeholder={t.searchTagsPlaceholder}
                  value={rawSearchQuery}
                  onChange={(e) => setRawSearchQuery(e.target.value)}
                  className="w-full pl-8 pr-3 py-1.5 text-xs rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-900 dark:text-white focus:outline-none focus:ring-1 focus:ring-[#243A73]"
                />
              </div>

              <select
                value={selectedRawCategory}
                onChange={(e) => setSelectedRawCategory(e.target.value)}
                className="px-3 py-1.5 text-xs rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-900 dark:text-white"
              >
                {rawCategories.map(cat => (
                  <option key={cat} value={cat}>
                    {cat} ({cat === 'ALL' ? rawTags.length : rawTags.filter(t => t.category === cat).length})
                  </option>
                ))}
              </select>
            </div>

            {/* Tags Table */}
            <div className="max-h-96 overflow-y-auto rounded-xl border border-slate-200 dark:border-slate-800">
              <table className="w-full text-left text-xs">
                <thead className="sticky top-0 bg-slate-100 dark:bg-slate-800 text-slate-800 dark:text-slate-200 font-bold border-b border-slate-200 dark:border-slate-700">
                  <tr>
                    <th className="py-2.5 px-3">Group</th>
                    <th className="py-2.5 px-3">Tag Name</th>
                    <th className="py-2.5 px-3">Value</th>
                    <th className="py-2.5 px-3 text-right">Action</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100 dark:divide-slate-800/60">
                  {filteredRawTags.length > 0 ? (
                    filteredRawTags.map((tag) => (
                      <tr key={tag.id} className="hover:bg-slate-50 dark:hover:bg-slate-800/40">
                        <td className="py-2 px-3 font-mono text-[11px] text-slate-500 shrink-0">
                          <span className="px-1.5 py-0.5 rounded bg-slate-200/80 dark:bg-slate-700/80 text-slate-800 dark:text-slate-200 font-semibold text-[10px]">
                            {tag.category}
                          </span>
                        </td>
                        <td className="py-2 px-3 font-semibold text-slate-900 dark:text-slate-100">
                          {tag.tag}
                        </td>
                        <td className="py-2 px-3 text-slate-700 dark:text-slate-300 break-all max-w-xs sm:max-w-md">
                          {tag.value}
                        </td>
                        <td className="py-2 px-3 text-right">
                          <button
                            onClick={() => copyToClipboard(tag.value, tag.id)}
                            className="p-1 rounded text-slate-400 hover:text-slate-700 dark:hover:text-slate-200 transition-colors cursor-pointer"
                            title={t.copyValue}
                          >
                            {copiedKey === tag.id ? <Check className="w-3.5 h-3.5 text-emerald-500" /> : <Copy className="w-3.5 h-3.5" />}
                          </button>
                        </td>
                      </tr>
                    ))
                  ) : (
                    <tr>
                      <td colSpan={4} className="py-6 text-center text-slate-500">
                        No tags found matching criteria.
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
